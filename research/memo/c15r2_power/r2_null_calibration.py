"""C15-R2 pre-run null calibration (synthetic only; NO model data). PI request of 2026-10-07 (D74).

Part 1 -- W3' COMPLETE-GATE false-positive rate
================================================
The complete W3' gate in a cell passes iff
  (a) validity controls pass: PC1, PC2, PC3, NC1, NC2; and
  (b) BB_J - BB_perp >= 0.15 and the 95% bootstrap lower bound (2.5th percentile, 1000 replicates,
      contexts x concepts) > 0, where BB_R is the fraction of sites meeting the site criterion
      [one-sided binomial p < 0.05 vs 1/8 on 192 trials AND acc_R >= max(0.30, 0.5 * acc_nat)].
Everything in (b) is simulated exactly as frozen (same trial counts, same bootstrap, acc_nat re-estimated in
every bootstrap replicate). In (a), PC2 is simulated; PC1, PC3, NC1 and NC2 are treated as passing, which can
only raise the false-positive rate (conservative upper bound).

Effective model (identification depends only on projections onto the 8 centred references; the common part
of the injection effect cancels under within-context centring):
  z[s, c, k, j] = a_R(s) * m_c^R * m_k^R * [j == k] + noise[s, c, k, j]
  noise = sqrt(rho) * xi_common[c, k, j] + sqrt(1 - rho) * xi[s, c, k, j]   (site-correlated; optional
          anisotropy across reference directions j, shared by all arms)
  centred over k within context c; trial correct iff argmax_j z == k.
  m_c^R, m_k^R ~ LogNormal(-sigma_m^2/2, sigma_m), drawn independently per arm (context- and concept-level
  clustering; arm-specific, i.e. least favourable). The natural benchmark (acc_nat) is the same model with a
  homogeneous signal a_nat.

PRE-DECLARED NULL FAMILY (J and perp generated by identical processes => equal true breadth; independent noise):
  a0 in {0.6, 0.9, 1.2, 1.5, 1.8, 2.2, 2.8} (noise-SD units; homogeneous population site accuracy 0.28, 0.37,
     0.48, 0.59, 0.69, 0.80, 0.92, i.e. across both floor regimes), profile in {uniform, offset-decay
     a0*exp(-o/6)},
  n_layers in {4, 11} (S = 48 or 132 sites), rho in {0.5, 0.9}, sigma_m in {0, 0.5, 1.0},
  natural benchmark in {acc_nat ~ 0.55 (floor = 0.30), acc_nat ~ 0.98 (floor ~ 0.49)},
  noise in {isotropic, anisotropic (rank-2 shared over j, condition ~ 5)}.
  672 configurations. Screening: 400 reps each. Re-estimation: the 10 highest-FPR configurations per ladder
  rung (union), 10,000 fresh reps each (independent seeds).

PRE-DECLARED DECISION RULE
  FPR* = max over re-estimated configurations of the complete-gate false-positive rate.
  * Acceptably controlled  <=>  FPR* - 1.96 * SE(FPR*) <= 0.05   -> keep the frozen thresholds (rung R0).
  * Materially exceeds     <=>  FPR* - 1.96 * SE(FPR*) >  0.05   -> adopt the FIRST rung below whose FPR*
    (point estimate) is <= 0.05:
       R0  diff >= 0.15, 2.5th-percentile bootstrap bound > 0   (frozen)
       R1  diff >= 0.15, 1st-percentile bound > 0
       R2  diff >= 0.20, 1st-percentile bound > 0
       R3  diff >= 0.25, 1st-percentile bound > 0
  Site criterion, bootstrap size and validity controls are not changed by any rung.
  Power under J > perp alternatives is reported for R0 and for the adopted rung (reporting only; it plays no
  role in the choice).

Part 2 -- W0b' gate (primary-position rule)
===========================================
Rule frozen in D74: the gate is decided at ONE pre-declared primary position, t_d (end of the bridge's
descriptive mention); t1 and t2 are reported only. Gate: two-hop acc >= 0.60 (not simulated; not inferential)
AND intermediate rate (among correct items) >= 0.40 AND paired lift (intermediate - mean of 5 foils) >= 0.20
AND one-sided 95% item-bootstrap (2000) lower bound of the lift > 0.
Null: the bridge is not more readable than same-type foils (equal per-item hit propensity, item heterogeneity
Beta-distributed, correlated across positions). Reported: FPR of the primary rule; for contrast only, the FPR of
the rejected uncorrected "any of three positions" rule; power at alternatives.

Usage: .venv/Scripts/python.exe research/memo/c15r2_power/r2_null_calibration.py [w3|w0b|all]
Output: research/memo/c15r2_power/r2_null_calibration.json
"""
import itertools
import json
import math
import os
import sys
import time
from multiprocessing import Pool

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "r2_null_calibration.json")

K, NCTX, NOFF = 8, 24, 12
NTR = K * NCTX                                   # 192 trials per site and arm
KCRIT = next(k for k in range(NTR + 1) if stats.binom.sf(k - 1, NTR, 1.0 / K) < 0.05)
FLOOR_ABS, FLOOR_REL = 0.30, 0.5
NBOOT = 1000
RUNGS = (("R0", 2.5, 0.15), ("R1", 1.0, 0.15), ("R2", 1.0, 0.20), ("R3", 1.0, 0.25))
MIN_DIFF = min(r[2] for r in RUNGS)

A0 = (0.6, 0.9, 1.2, 1.5, 1.8, 2.2, 2.8)
PROFILES = ("uniform", "offset_decay")
NLAY = (4, 11)
RHO = (0.5, 0.9)
SIGMA_M = (0.0, 0.5, 1.0)
NAT = ("acc_nat_0.55", "acc_nat_0.98")
NOISE = ("iso", "aniso")
N_SCREEN, N_REEST, TOP = 400, 10000, 10


def acc_of_signal(a, n=400000, seed=0):
    """Population 8-way accuracy for homogeneous signal a (iid noise, centring over k)."""
    r = np.random.default_rng(seed)
    z = r.standard_normal((n // K, K, K))
    z[:, np.arange(K), np.arange(K)] += a
    z -= z.mean(1, keepdims=True)
    return float((z.argmax(-1) == np.arange(K)[None]).mean())


def calibrate(target):
    lo, hi = 0.0, 8.0
    for _ in range(30):
        mid = 0.5 * (lo + hi)
        (lo, hi) = (mid, hi) if acc_of_signal(mid) < target else (lo, mid)
    return 0.5 * (lo + hi)


A_NAT = None


def aniso_L(rng):
    B = rng.standard_normal((K, 2))
    S = np.eye(K) + 2.0 * (B @ B.T) / K
    S *= K / np.trace(S)
    return np.linalg.cholesky(S)


def correct(rng, a_s, m_c, m_k, rho, L):
    """Boolean [S, NCTX, K]: trial (c, k) at site s identified correctly."""
    S = len(a_s)
    xi_c = rng.standard_normal((NCTX, K, K), dtype=np.float32)
    z = math.sqrt(1 - rho) * rng.standard_normal((S, NCTX, K, K), dtype=np.float32) + math.sqrt(rho) * xi_c[None]
    if L is not None:
        z = z @ L.T.astype(np.float32)
    idx = np.arange(K)
    z[:, :, idx, idx] += (a_s[:, None, None] * m_c[None, :, None] * m_k[None, None, :]).astype(np.float32)
    z -= z.mean(axis=2, keepdims=True)
    return z.argmax(-1) == idx[None, None, :]


def site_pass(cnt_R, cnt_nat):
    """cnt_*: [..., S] counts out of NTR. Site criterion (significance AND effect-size floor)."""
    acc, accn = cnt_R / NTR, cnt_nat / NTR
    return (cnt_R >= KCRIT) & (acc >= np.maximum(FLOOR_ABS, FLOOR_REL * accn) - 1e-12)


def lognorm(rng, sig, n):
    if sig == 0:
        return np.ones(n)
    return np.exp(sig * rng.standard_normal(n) - 0.5 * sig * sig)


def profile(kind, a0, nlay):
    o = np.repeat(np.arange(NOFF)[:, None], nlay, 1).reshape(-1)
    return a0 * (np.ones_like(o, float) if kind == "uniform" else np.exp(-o / 6.0))


def one_rep(rng, cfg, aJ=None, aP=None):
    a0, prof, nlay, rho, sig, nat, noise = cfg
    aJ = profile(prof, a0, nlay) if aJ is None else aJ
    aP = profile(prof, a0, nlay) if aP is None else aP
    L = aniso_L(rng) if noise == "aniso" else None
    S = len(aJ)
    XJ = correct(rng, aJ, lognorm(rng, sig, NCTX), lognorm(rng, sig, K), rho, L)
    XP = correct(rng, aP, lognorm(rng, sig, NCTX), lognorm(rng, sig, K), rho, L)
    XN = correct(rng, np.full(S, A_NAT[nat]), np.ones(NCTX), np.ones(K), rho, L)
    cJ, cP, cN = (X.sum((1, 2)) for X in (XJ, XP, XN))
    pc2 = np.mean((cN >= KCRIT) & (cN / NTR >= FLOOR_ABS)) >= 0.5
    diff = site_pass(cJ, cN).mean() - site_pass(cP, cN).mean()
    out = {"diff": float(diff), "pc2": bool(pc2), "acc_nat": float(cN.mean() / NTR),
           "accJ": float(cJ.mean() / NTR), "pass": {r[0]: False for r in RUNGS}}
    if diff >= MIN_DIFF and pc2:
        wc = rng.multinomial(NCTX, np.full(NCTX, 1.0 / NCTX), size=NBOOT).astype(np.float32)
        wk = rng.multinomial(K, np.full(K, 1.0 / K), size=NBOOT).astype(np.float32)
        bc = {n: np.einsum("bc,bk,sck->bs", wc, wk, X.astype(np.float32), optimize=True)
              for n, X in (("J", XJ), ("P", XP), ("N", XN))}
        d = site_pass(np.rint(bc["J"]), np.rint(bc["N"])).mean(1) - site_pass(np.rint(bc["P"]), np.rint(bc["N"])).mean(1)
        for name, q, dmin in RUNGS:
            out["pass"][name] = bool(diff >= dmin and np.percentile(d, q) > 0)
    return out


def run_cfg(args):
    cfg, n, seed = args
    rng = np.random.default_rng(seed)
    res = [one_rep(rng, cfg) for _ in range(n)]
    return {"cfg": list(cfg), "n": n,
            "fpr": {r[0]: float(np.mean([x["pass"][r[0]] for x in res])) for r in RUNGS},
            "p_pc2": float(np.mean([x["pc2"] for x in res])),
            "mean_acc_site_J": float(np.mean([x["accJ"] for x in res])),
            "mean_acc_nat": float(np.mean([x["acc_nat"] for x in res])),
            "p_diff_ge_0.15": float(np.mean([x["diff"] >= 0.15 for x in res]))}


def run_power(args):
    name, cfg, aJ0, aP0, n, seed = args
    rng = np.random.default_rng(seed)
    a0, prof, nlay = cfg[0], cfg[1], cfg[2]
    res = [one_rep(rng, cfg, aJ=profile(prof, aJ0, nlay), aP=profile(prof, aP0, nlay)) for _ in range(n)]
    return {"name": name, "cfg": list(cfg), "aJ0": aJ0, "aP0": aP0, "n": n,
            "power": {r[0]: float(np.mean([x["pass"][r[0]] for x in res])) for r in RUNGS},
            "mean_diff": float(np.mean([x["diff"] for x in res]))}


def part_w3(pool):
    global A_NAT
    t0 = time.time()
    grid = list(itertools.product(A0, PROFILES, NLAY, RHO, SIGMA_M, NAT, NOISE))
    ss = np.random.SeedSequence(9502)
    seeds = ss.spawn(len(grid) + 2000)
    scr = pool.map(run_cfg, [(g, N_SCREEN, seeds[i]) for i, g in enumerate(grid)], chunksize=4)
    t1 = time.time()
    pick = set()
    for name, _, _ in RUNGS:
        for r in sorted(scr, key=lambda r: -r["fpr"][name])[:TOP]:
            pick.add(tuple(r["cfg"]))
    pick = sorted(pick, key=lambda c: grid.index(tuple(c)))
    re_seeds = seeds[len(grid): len(grid) + len(pick)]
    # 10,000 reps per configuration, split into 10 chunks for the pool
    jobs = [(tuple(c), N_REEST // 10, re_seeds[i].spawn(10)[j]) for i, c in enumerate(pick) for j in range(10)]
    chunks = pool.map(run_cfg, jobs, chunksize=1)
    rees = []
    for i, c in enumerate(pick):
        part = chunks[10 * i: 10 * i + 10]
        rees.append({"cfg": list(c), "n": N_REEST,
                     "fpr": {r[0]: float(np.mean([p["fpr"][r[0]] for p in part])) for r in RUNGS},
                     "p_pc2": float(np.mean([p["p_pc2"] for p in part])),
                     "mean_acc_site_J": float(np.mean([p["mean_acc_site_J"] for p in part])),
                     "p_diff_ge_0.15": float(np.mean([p["p_diff_ge_0.15"] for p in part]))})
    worst = {}
    for name, _, _ in RUNGS:
        w = max(rees, key=lambda r: r["fpr"][name])
        f = w["fpr"][name]
        se = math.sqrt(max(f * (1 - f), 1e-12) / N_REEST)
        worst[name] = {"fpr_star": f, "se": se, "lower95": f - 1.96 * se, "cfg": w["cfg"]}
    controlled = worst["R0"]["lower95"] <= 0.05
    adopted = "R0" if controlled else next((r[0] for r in RUNGS[1:] if worst[r[0]]["fpr_star"] <= 0.05), None)
    # power (reporting only)
    pw_cfgs = []
    for nat in NAT:
        for nlay in NLAY:
            base = (1.5, "uniform", nlay, 0.9, 0.5, nat, "iso")
            for aJ0, aP0 in ((1.8, 0.9), (2.2, 0.9), (2.8, 0.9), (2.8, 1.5), (2.2, 1.5)):
                pw_cfgs.append((f"{nat},S={NOFF * nlay},aJ={aJ0},aP={aP0}", base, aJ0, aP0))
            dec = (1.5, "offset_decay", nlay, 0.9, 0.5, nat, "iso")
            for aJ0, aP0 in ((2.8, 1.2), (4.0, 1.5)):
                pw_cfgs.append((f"{nat},S={NOFF * nlay},decay,aJ={aJ0},aP={aP0}", dec, aJ0, aP0))
    ps = seeds[len(grid) + len(pick): len(grid) + len(pick) + len(pw_cfgs)]
    power = pool.map(run_power, [(n, c, a, b, 1000, ps[i]) for i, (n, c, a, b) in enumerate(pw_cfgs)])
    return {"a_nat": A_NAT, "kcrit": KCRIT, "n_boot": NBOOT, "rungs": [list(r) for r in RUNGS],
            "grid_size": len(grid), "screen_reps": N_SCREEN, "reest_reps": N_REEST,
            "screen_max_fpr": {r[0]: max(x["fpr"][r[0]] for x in scr) for r in RUNGS},
            "screen_mean_fpr": {r[0]: float(np.mean([x["fpr"][r[0]] for x in scr])) for r in RUNGS},
            "reestimated": rees, "worst": worst, "controlled_at_R0": controlled, "adopted_rung": adopted,
            "power": power, "screen": scr, "seconds": {"screen": t1 - t0, "total": time.time() - t0}}


