def w0b_rep(rng, n, q_b, q_f, conc, rho_pos, multi):
    """Per item latent propensity (Beta with concentration conc); positions share it with weight rho_pos.
    Returns pass of the primary rule and of the (rejected) uncorrected any-of-3 rule."""
    def beta(mean):
        a = max(mean * conc, 1e-3)
        b = max((1 - mean) * conc, 1e-3)
        return rng.beta(a, b, size=n)
    shared_b, shared_f = beta(q_b), beta(q_f)
    hits_b, hits_f = [], []
    for p in range(3 if multi else 1):
        pb = rho_pos * shared_b + (1 - rho_pos) * beta(q_b)
        pf = rho_pos * shared_f + (1 - rho_pos) * beta(q_f)
        hits_b.append(rng.random(n) < pb)
        hits_f.append((rng.random((n, 5)) < pf[:, None]).mean(1))

    def gate(hb, hf):
        rate, lift_i = hb.mean(), hb - hf
        lift = lift_i.mean()
        if rate < 0.40 or lift < 0.20:
            return False
        idx = rng.integers(0, n, (2000, n))
        return bool(np.percentile(lift_i[idx].mean(1), 5.0) > 0)
    prim = gate(hits_b[0], hits_f[0])
    anyp = any(gate(hits_b[p], hits_f[p]) for p in range(len(hits_b))) if multi else prim
    return prim, anyp


def part_w0b():
    rng = np.random.default_rng(9502)
    out = {"null": [], "alt": []}
    for n in (30, 45, 60):
        for q in (0.1, 0.25, 0.4, 0.55):
            for conc in (2.0, 10.0):
                for rho_pos in (0.0, 0.7):
                    r = [w0b_rep(rng, n, q, q, conc, rho_pos, True) for _ in range(4000)]
                    out["null"].append({"n_correct": n, "q": q, "conc": conc, "rho_pos": rho_pos,
                                        "fpr_primary": float(np.mean([x[0] for x in r])),
                                        "fpr_uncorrected_any3": float(np.mean([x[1] for x in r]))})
    for n in (30, 45, 60):
        for qb, qf in ((0.45, 0.10), (0.55, 0.20), (0.60, 0.15), (0.40, 0.25), (0.70, 0.30)):
            r = [w0b_rep(rng, n, qb, qf, 10.0, 0.7, False) for _ in range(2000)]
            out["alt"].append({"n_correct": n, "q_bridge": qb, "q_foil": qf,
                               "power_primary": float(np.mean([x[0] for x in r]))})
    out["max_fpr_primary"] = max(x["fpr_primary"] for x in out["null"])
    out["max_fpr_uncorrected_any3"] = max(x["fpr_uncorrected_any3"] for x in out["null"])
    return out


def _init(a_nat):
    global A_NAT
    A_NAT = a_nat


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    res = json.load(open(OUT)) if os.path.isfile(OUT) else {}
    if which in ("w3", "all"):
        a_nat = {"acc_nat_0.55": calibrate(0.55), "acc_nat_0.98": calibrate(0.98)}
        A_NAT = a_nat
        with Pool(min(12, os.cpu_count() or 4), initializer=_init, initargs=(a_nat,)) as pool:
            res["w3_complete_gate"] = part_w3(pool)
        w = res["w3_complete_gate"]
        print(json.dumps({"worst": w["worst"], "controlled_at_R0": w["controlled_at_R0"],
                          "adopted_rung": w["adopted_rung"], "seconds": w["seconds"]}, indent=1), flush=True)
    if which in ("w0b", "all"):
        res["w0b_primary_rule"] = part_w0b()
        print(json.dumps({k: res["w0b_primary_rule"][k] for k in ("max_fpr_primary", "max_fpr_uncorrected_any3")}),
              flush=True)
    res["kcrit_192"] = KCRIT
    with open(OUT, "w") as f:
        json.dump(res, f, indent=1)
    print("wrote", OUT)
