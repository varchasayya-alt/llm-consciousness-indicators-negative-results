"""REPORT phase: compact tables and a verdict JSON from the S0/S1 results (no new computation)."""
from __future__ import annotations

import json
import os

from . import config as C


def _load(name):
    p = os.path.join(C.RESULTS, name)
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def _f(v, nd=3):
    if v is None:
        return "NA"
    if isinstance(v, bool):
        return "pass" if v else "FAIL"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def write(log=print):
    s0, s1b, s1c, s1a = _load("s0_final.json"), _load("s1b.json"), _load("s1c.json"), _load("s1a.json")
    L = ["# C16 Stage 0 / Stage 1 tables (generated by run_c16.py REPORT)", ""]
    verdict = {}
    if s0:
        sm = s0["summary"]
        fin = s0.get(sm["final_format"]) if sm["final_format"] else s0.get("F2") or s0.get("F1")
        verdict["S0"] = sm
        L += ["## Stage 0 (Qwen2.5-0.5B-Instruct)", "", f"Final format: {sm['final_format']}", ""]
        m2 = fin.get("M2", {})
        L += ["| Consumer | text acc | eligible | native (elig.) | kappa | full content gain | CT oracle | NC shift f(X') | bundle B4 gain |",
              "|---|---|---|---|---|---|---|---|---|"]
        m4 = fin.get("M4", {})
        for j in C.ALL_CONSUMERS:
            sw = m4.get("swap", {}).get(j, {})
            shift = None
            if sw.get("P_nc_sw") is not None and sw.get("P_nat_sw") is not None:
                shift = sw["P_nc_sw"] - sw["P_nat_sw"]
            b4 = m4.get("bundles", {}).get("B4", {}).get("full_gain", {}).get(j)
            L.append(f"| {j} | {_f(m2.get('text_by_consumer', {}).get(j))} | {_f(m2.get('eligible_rate', {}).get(j))} | "
                     f"{_f(m2.get('native_eligible', {}).get(j))} | {_f(m2.get('kappa', {}).get(j))} | "
                     f"{_f(m4.get('content_full_gain', {}).get(j))} | {_f(sw.get('CT'))} | {_f(shift)} | {_f(b4)} |")
        L += ["", f"Copy (producer competence) by producer: {m2.get('copy_by_producer')}",
              f"V0 decodability at L_w={fin.get('M1', {}).get('L_w')}: {fin.get('V0')}",
              f"l_o={sm['l_o']}  read layers={sm['read_layers']}",
              f"r_X (geo-mean)={_f(sm['rX_geomean'])}; r_B={sm['rB_geomean']}",
              f"Gates: V1={sm['V1']}", f"V2={sm['V2']}", f"W={sm['W']}",
              f"Core instrument-valid: {sm['core_instrument_valid']}; phase diagram measurable: {sm['phase_diagram_measurable']}",
              f"Engineering: {fin.get('engineering')}", ""]
    if s1b:
        verdict["S1b_pass"] = s1b["pass"]
        L += ["## S1b rank recovery", "", "| Case | true | r* | within x2 |", "|---|---|---|---|"]
        for k, v in s1b.items():
            if isinstance(v, dict):
                L.append(f"| {k} | {v['r_true']} | {v['r_star']} | {_f(v['within_x2'])} |")
        L.append("")
    if s1c:
        verdict["S1c_1_pass"] = s1c.get("S1c_1_pass")
        verdict["S1c_2"] = s1c.get("S1c_2")
        L += ["## S1c planted system (pipeline outputs only; not evidence)", "",
              f"S1c-1 (planted instrument gates): {s1c.get('S1c_1_pass')}", f"Arm config: {s1c.get('arm_config')}",
              f"Native (no workspace) acc: {s1c.get('native')}", f"S1c-2: {s1c.get('S1c_2')}", ""]
        if "core" in s1c:
            L += ["| Arm | seed | TR acc | TR CT | HO CT | U CT | U acc | HO acc ablated |", "|---|---|---|---|---|---|---|---|"]
            for kind, recs in s1c["core"].items():
                for r in recs:
                    L.append(f"| {kind} | {r['seed']} | {_f(r['TR']['acc'])} | {_f(r['TR']['CT'])} | {_f(r['HO']['CT'])} | "
                             f"{_f(r['U']['CT'])} | {_f(r['U']['acc'])} | {_f(r['HO']['acc_ablate'])} |")
            L.append("")
        if "pilot" in s1c:
            L += ["Pilot T(c,S) = CT_U (mean over seeds):", "", "| cell | d_w | CT_U per seed | mean |", "|---|---|---|---|"]
            for k, recs in s1c["pilot"].items():
                vals = [r["U"]["CT"] for r in recs]
                good = [v for v in vals if v is not None]
                L.append(f"| {k} | {recs[0]['d_w']} | {', '.join(_f(v) for v in vals)} | {_f(sum(good)/len(good) if good else None)} |")
            L += ["", f"sigma_seed (logit): {s1c.get('sigma_seed_logit')}", ""]
    if s1a:
        verdict["S1a"] = {k: s1a.get(k) for k in ("core_final_gates", "core_final_fpr", "core_final_power",
                                                  "hcd_minimal", "hcd_central_recommended", "stage2_run_cpu_h_estimate")}
        L += ["## S1a power and complete-gate FPR", "", f"Inputs: {s1a['inputs']}",
              f"Core final margins: {s1a['core_final_gates']}; max over-claim FPR {_f(s1a['core_final_fpr'])}; "
              f"min power {_f(s1a['core_final_power'])}", "",
              "| n_s | items/cell | min power | max wrong-account | CPU-h (4 cells) | CPU-h (25 cells) |", "|---|---|---|---|---|---|"]
        for h in s1a["hcd"]:
            L.append(f"| {h['n_s']} | {h['m_cell']} | {_f(h['min_power'])} | {_f(h['max_wrong_account'])} | "
                     f"{_f(h['cpu_h_4cells'], 1)} | {_f(h['cpu_h_full_grid'], 1)} |")
        L += ["", f"H-CD minimal design: {s1a['hcd_minimal']}; central recommended: {s1a['hcd_central_recommended']}", ""]
    with open(os.path.join(C.RESULTS, "s0s1_tables.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    with open(os.path.join(C.RESULTS, "verdict_s0s1.json"), "w", encoding="utf-8") as f:
        json.dump(verdict, f, indent=1, default=str)
    log("REPORT written")
